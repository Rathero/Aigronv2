function mulberry32(a){return function(){a|=0;a=a+0x6D2B79F5|0;let t=Math.imul(a^a>>>15,1|a);t=t+Math.imul(t^t>>>7,61|t)^t;return((t^t>>>14)>>>0)/4294967296}}
const PALETTES = [
  ["#2b0a0a","#7a1f1f","#e8472b","#ff8c42","#ffd34e"],
  ["#0a1a2b","#1f4d7a","#2bb5e8","#7ef2ff","#e0fbff"],
  ["#150a2b","#3d1f7a","#7a2be8","#c084fc","#f3e8ff"],
  ["#0a2b14","#1f7a3d","#2be86b","#7ef29a","#dcffe8"],
  ["#2b270a","#7a6e1f","#e8d22b","#fff07e","#fffbe0"],
  ["#2b0a1f","#7a1f57","#e82b9d","#ff7ed2","#ffe0f3"]
];
function genGrid(seed, palLen){
  const rnd = mulberry32(seed); const S=16; const grid=[];
  for(let y=0;y<S;y++){grid[y]=[];for(let x=0;x<S/2;x++){
    const d = Math.hypot(x-S/4,(y-S/2)*0.8)/(S/2.6);
    grid[y][x] = (rnd() > d*0.85) ? 1+Math.floor(rnd()*(palLen-1)) : 0;
  }}
  for(let y=1;y<S-1;y++)for(let x=1;x<S/2-1;x++){
    if(grid[y][x] && !grid[y-1][x] && !grid[y+1][x] && !grid[y][x-1] && !grid[y][x+1]) grid[y][x]=0;
  }
  const ey=4+Math.floor(rnd()*4), ex=2+Math.floor(rnd()*3);
  grid[ey][ex]=0; if(grid[ey][ex+1]!==undefined) grid[ey][ex+1]=palLen-1;
  return grid;
}
function drawCreature(canvas, seed, palIdx){
  const S=16, pal=PALETTES[palIdx % PALETTES.length];
  const grid = genGrid(seed, pal.length);
  // full 16x16 mirrored
  const full=[];
  for(let y=0;y<S;y++){full[y]=[];for(let x=0;x<S;x++){full[y][x] = x<S/2 ? grid[y][x] : grid[y][S-1-x];}}
  const ctx=canvas.getContext('2d');
  canvas.width=S+2; canvas.height=S+2; // margen para contorno
  ctx.clearRect(0,0,S+2,S+2);
  // contorno oscuro (silueta legible)
  ctx.fillStyle="#05050c";
  for(let y=0;y<S;y++)for(let x=0;x<S;x++){
    if(!full[y][x]) continue;
    for(const [dx,dy] of [[1,0],[-1,0],[0,1],[0,-1]]){
      const nx=x+dx, ny=y+dy;
      if(nx<0||ny<0||nx>=S||ny>=S||!full[ny][nx]) ctx.fillRect(nx+1,ny+1,1,1);
    }
  }
  for(let y=0;y<S;y++)for(let x=0;x<S;x++){
    const v=full[y][x]; if(!v) continue;
    ctx.fillStyle=pal[v-1]||pal[0];
    ctx.fillRect(x+1,y+1,1,1);
  }
}


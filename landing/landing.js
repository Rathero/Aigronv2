function renderAltar(data){
  const old=document.getElementById('altar-canvas');
  if(data && (data.image_url||data.image_thumb_url)){
    const img=document.createElement('img');
    img.id='altar-canvas'; // hereda el CSS del altar (tamaño, flotación, sombra)
    img.src=resolveArt(data.image_url||data.image_thumb_url);
    img.alt=data.name||'';
    old.replaceWith(img);
  } else {
    let cv=old;
    if(old.tagName!=='CANVAS'){ cv=document.createElement('canvas'); cv.id='altar-canvas'; old.replaceWith(cv); }
    if(!drawRealTpl(cv, data, 12)) drawCreature(cv, data?seedNum(data.art_seed):992617, 5);
  }
  if(data){
    if(data.name) document.getElementById('altar-name').textContent=String(data.name).toUpperCase();
    if(data.lore) document.getElementById('altar-lore').textContent='«'+data.lore+'»';
  }
}

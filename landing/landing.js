/* ================= datos reales del juego =================
   Si la landing se sirve desde el propio servidor (/landing), API_BASE es el
   mismo origen. Para desplegarla aparte, define window.AIGRONS_API antes de
   este script. Sin API, la página funciona igual con contenido procedural. */
const API_BASE = window.AIGRONS_API || '';
function resolveArt(u){ return /^https?:/i.test(u) ? u : API_BASE + u; }
(async function loadRealData(){
  try{
    const ctl=new AbortController(); setTimeout(()=>ctl.abort(),6000);
    const r=await fetch(API_BASE+'/api/landing',{signal:ctl.signal});
    if(!r.ok) throw new Error(r.status);
    const d=await r.json();
    if(!d || !d.season) throw new Error('bad payload');
    window.REAL=d;
    renderAltar(d.unique);
    buildAlbum(d.albumSample, d.season.discovered, d.season.total);
    updateSeasonChip();
  }catch(e){ console.warn('[landing] sin datos reales (', e && e.message, ') — mostrando contenido de respaldo'); }
})();


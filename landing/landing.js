function buildAlbum(sample, discovered, total){
  const cont=document.getElementById('stickers');
  cont.innerHTML='';
  const rnd=mulberry32(20260612);
  const items=(sample&&sample.length)
    ? sample.map(t=>({tpl:t, seed:seedNum(t.art_seed), rarity:t.rarity, thumb:t.image_thumb_url}))
    : Array.from({length:24},(_,i)=>({tpl:null, seed:7000+Math.floor(rnd()*999999), rarity:null, thumb:null}));
  const T=total||180, D=(discovered!=null)?discovered:64;
  const frac=Math.max(0.08,Math.min(0.95,D/T));
  const rcls=r=> r==='LEGENDARIA'?'s-leg' : r==='EPICA'?'s-epic' : r==='RARA'?'s-rare' : '';
  items.forEach((it,i)=>{
    const d=document.createElement('div');
    // reparto determinista de "descubiertas", proporcional al avance real de la comunidad
    const known=(((i+1)*2654435761)>>>0)%1000 < frac*1000;
    const fallbackR= i===2?'LEGENDARIA' : (i===7||i===15)?'EPICA' : (i%5===0?'RARA':'');
    d.className='sticker '+(known ? rcls(it.rarity||fallbackR) : 'unknown');
    if(known && it.thumb){
      const img=document.createElement('img');
      img.src=resolveArt(it.thumb);
      img.style.cssText='width:78%;height:78%;image-rendering:pixelated;border-radius:6px;object-fit:contain';
      d.appendChild(img);
    } else {
      const c=document.createElement('canvas'); d.appendChild(c);
      // Sprite REAL del juego si hay datos (las 'unknown' las oscurece el CSS:
      // misma forma, en negro — igual que las siluetas del álbum de la app).
      if(!drawRealTpl(c, it.tpl, 6)) drawCreature(c, it.seed, i%6);
    }
    cont.appendChild(d);
  });
  const fill=document.getElementById('album-fill'), num=document.getElementById('album-n');
  document.getElementById('album-total').textContent=T;
  const obs=new IntersectionObserver(es=>es.forEach(e=>{
    if(!e.isIntersecting) return; obs.disconnect();
    fill.style.width=Math.round(D/T*100)+'%';
    let v=0; const step=Math.max(1,Math.round(D/32));
    const t=setInterval(()=>{ v+=step; if(v>=D){v=D;clearInterval(t);} num.textContent=v; },28);
  }),{threshold:0.35});
  obs.observe(fill);
}
buildAlbum(null);

